function abilityTrait(
  id: string,
  name: string,
  description: string,
  category: TraitDefinition["category"],
  polarity: TraitDefinition["polarity"],
  ability: AbilityKey,
  value: number,
  rarity: number,
): TraitDefinition {
  return {
    id,
    name,
    description,
    category,
    polarity,
    rarity,
    effects: [{ type: "ability-modifier", ability, value }],
    tags: [ability],
  };
}

function situationTrait(
  id: string,
  name: string,
  description: string,
  category: TraitDefinition["category"],
  polarity: TraitDefinition["polarity"],
  situation: "close-set" | "behind" | "ahead" | "first-match" | "tournament" | "serve" | "receive" | "attack" | "block",
  value: number,
  rarity: number,
): TraitDefinition {
  return {
    id,
    name,
    description,
    category,
    polarity,
    rarity,
    effects: [{ type: "situation-modifier", situation, value }],
    tags: [situation],
  };
}

